import type { Locale } from "@/lib/i18n/config";

export const WATERMARK_URL = "https://jutaone.biz/?utm_source=ai_caption&utm_medium=social";

/** Viral-loop watermark per locale (Boss + Linda spec). Appended at the very bottom. */
export const WATERMARK_TEXT: Record<Locale, string> = {
  ms: `\n\n✨ Dijana oleh AI JutaOne.Biz: ${WATERMARK_URL}`,
  en: `\n\n✨ Generated by JutaOne.Biz AI: ${WATERMARK_URL}`,
  id: `\n\n✨ Dibuat oleh AI JutaOne.Biz: ${WATERMARK_URL}`,
};

const ALL_WATERMARKS = Object.values(WATERMARK_TEXT);

/** Append the locale watermark unless already present (idempotent). */
export function appendWatermark(caption: string, locale: Locale): string {
  const clean = caption.trimEnd();
  if (ALL_WATERMARKS.some((mark) => clean.endsWith(mark.trim()))) return caption;
  return `${clean}${WATERMARK_TEXT[locale] ?? WATERMARK_TEXT.en}`;
}

/** Remove any known watermark suffix (for the opt-out toggle). */
export function stripWatermark(caption: string): string {
  let clean = caption.trimEnd();
  for (const mark of ALL_WATERMARKS) {
    const trimmed = mark.trim();
    if (clean.endsWith(trimmed)) {
      clean = clean.slice(0, -trimmed.length).trimEnd();
    }
  }
  return clean;
}

/** Final share text honoring the "include link" toggle. */
export function withWatermarkChoice(caption: string, locale: Locale, include: boolean): string {
  const base = stripWatermark(caption);
  return include ? appendWatermark(base, locale) : base;
}
